import { describe, it, expect, beforeAll, afterAll } from "bun:test"
import { generateTypes } from "./generate-types"
import { writeFile, mkdir, rm } from "fs/promises"
import { readFile } from "fs/promises"
import { join } from "path"
import { tmpdir } from "os"

const testDir = join(tmpdir(), `pgstrap-test-${Date.now()}`)
const migrationsDir = join(testDir, "migrations")
const outputFile = join(testDir, "db-types.ts")

beforeAll(async () => {
  await mkdir(migrationsDir, { recursive: true })

  // Write test migration files
  await writeFile(
    join(migrationsDir, "001_create_users.sql"),
    `
    CREATE TABLE users (
      id SERIAL PRIMARY KEY,
      name TEXT NOT NULL,
      email TEXT NOT NULL UNIQUE,
      age INTEGER,
      created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
    );
    `
  )

  await writeFile(
    join(migrationsDir, "002_create_posts.sql"),
    `
    CREATE TYPE post_status AS ENUM ('draft', 'published', 'archived');

    CREATE TABLE posts (
      id SERIAL PRIMARY KEY,
      user_id INTEGER NOT NULL REFERENCES users(id),
      title TEXT NOT NULL,
      body TEXT,
      status post_status NOT NULL DEFAULT 'draft',
      published_at TIMESTAMP WITH TIME ZONE,
      metadata JSONB
    );
    `
  )
})

afterAll(async () => {
  await rm(testDir, { recursive: true, force: true })
})

describe("generateTypes", () => {
  it("generates TypeScript types from migrations without a running Postgres", async () => {
    await generateTypes({ migrationsDir, outputFile })

    const content = await readFile(outputFile, "utf-8")

    // Should contain auto-generated header
    expect(content).toContain("auto-generated by pgstrap")

    // Should contain enum type
    expect(content).toContain("PostStatus")
    expect(content).toContain(`"draft"`)
    expect(content).toContain(`"published"`)
    expect(content).toContain(`"archived"`)

    // Should contain Users interface
    expect(content).toContain("interface Users")
    expect(content).toContain("id?")
    expect(content).toContain("name: string")
    expect(content).toContain("email: string")
    expect(content).toContain("age?: number | null")

    // Should contain Posts interface
    expect(content).toContain("interface Posts")
    expect(content).toContain("title: string")
    expect(content).toContain("status?: PostStatus")

    // Should contain Database interface
    expect(content).toContain("interface Database")
    expect(content).toContain("users: Users")
    expect(content).toContain("posts: Posts")
  })

  it("handles missing migrations directory gracefully", async () => {
    const emptyOutputFile = join(testDir, "empty-types.ts")
    await generateTypes({
      migrationsDir: join(testDir, "nonexistent"),
      outputFile: emptyOutputFile,
    })

    const content = await readFile(emptyOutputFile, "utf-8")
    expect(content).toContain("auto-generated by pgstrap")
    expect(content).toContain("interface Database")
  })
})
