import { PGlite } from "@electric-sql/pglite"
import { readdir, readFile, writeFile } from "fs/promises"
import { join, extname } from "path"

interface GenerateTypesOptions {
  migrationsDir: string
  outputFile: string
}

interface ColumnInfo {
  table_name: string
  column_name: string
  data_type: string
  udt_name: string
  is_nullable: string
  column_default: string | null
}

interface EnumInfo {
  enum_name: string
  enum_values: string[]
}

export async function generateTypes(options: GenerateTypesOptions) {
  const { migrationsDir, outputFile } = options

  console.log(`pgstrap: Using in-memory PGlite (no Postgres required)`)
  console.log(`pgstrap: Reading migrations from ${migrationsDir}`)

  const db = new PGlite()

  // Read and sort migration files
  let migrationFiles: string[] = []
  try {
    const files = await readdir(migrationsDir)
    migrationFiles = files
      .filter((f) => extname(f) === ".sql")
      .sort()
  } catch (err: any) {
    if (err.code === "ENOENT") {
      console.warn(`pgstrap: Migrations directory not found: ${migrationsDir}`)
      console.warn(`pgstrap: Generating empty types file`)
    } else {
      throw err
    }
  }

  // Run each migration
  for (const file of migrationFiles) {
    const filePath = join(migrationsDir, file)
    const sql = await readFile(filePath, "utf-8")
    console.log(`pgstrap: Running migration: ${file}`)
    try {
      await db.exec(sql)
    } catch (err: any) {
      console.error(`pgstrap: Error running migration ${file}: ${err.message}`)
      throw err
    }
  }

  // Introspect the schema
  const columnsResult = await db.query<ColumnInfo>(`
    SELECT
      c.table_name,
      c.column_name,
      c.data_type,
      c.udt_name,
      c.is_nullable,
      c.column_default
    FROM information_schema.columns c
    JOIN information_schema.tables t
      ON c.table_name = t.table_name
      AND c.table_schema = t.table_schema
    WHERE c.table_schema = 'public'
      AND t.table_type = 'BASE TABLE'
    ORDER BY c.table_name, c.ordinal_position
  `)

  // Introspect enums
  const enumsResult = await db.query<{ enum_name: string; enum_value: string }>(`
    SELECT
      t.typname AS enum_name,
      e.enumlabel AS enum_value
    FROM pg_type t
    JOIN pg_enum e ON t.oid = e.enumtypid
    JOIN pg_catalog.pg_namespace n ON n.oid = t.typnamespace
    WHERE n.nspname = 'public'
    ORDER BY t.typname, e.enumsortorder
  `)

  // Group columns by table
  const tableMap = new Map<string, ColumnInfo[]>()
  for (const row of columnsResult.rows) {
    if (!tableMap.has(row.table_name)) {
      tableMap.set(row.table_name, [])
    }
    tableMap.get(row.table_name)!.push(row)
  }

  // Group enum values by enum name
  const enumMap = new Map<string, string[]>()
  for (const row of enumsResult.rows) {
    if (!enumMap.has(row.enum_name)) {
      enumMap.set(row.enum_name, [])
    }
    enumMap.get(row.enum_name)!.push(row.enum_value)
  }

  // Generate TypeScript
  const lines: string[] = []
  lines.push(`// This file is auto-generated by pgstrap. Do not edit manually.`)
  lines.push(`// Generated at: ${new Date().toISOString()}`)
  lines.push(``)

  // Generate enum types
  if (enumMap.size > 0) {
    lines.push(`// Enum Types`)
    for (const [enumName, values] of enumMap) {
      const typeName = toPascalCase(enumName)
      lines.push(`export type ${typeName} = ${values.map((v) => JSON.stringify(v)).join(" | ")}`)
    }
    lines.push(``)
  }

  // Generate table row types
  if (tableMap.size > 0) {
    lines.push(`// Table Row Types`)
    for (const [tableName, columns] of tableMap) {
      const typeName = toPascalCase(tableName)
      lines.push(`export interface ${typeName} {`)
      for (const col of columns) {
        const tsType = pgTypeToTs(col.data_type, col.udt_name, enumMap)
        const nullable = col.is_nullable === "YES"
        const optional = nullable || col.column_default !== null
        lines.push(
          `  ${escapeIdentifier(col.column_name)}${optional ? "?" : ""}: ${tsType}${nullable ? " | null" : ""}`
        )
      }
      lines.push(`}`)
      lines.push(``)
    }
  }

  // Generate a Database type that maps table names to row types
  lines.push(`// Database Schema`)
  lines.push(`export interface Database {`)
  for (const [tableName] of tableMap) {
    const typeName = toPascalCase(tableName)
    lines.push(`  ${escapeIdentifier(tableName)}: ${typeName}`)
  }
  lines.push(`}`)
  lines.push(``)

  const output = lines.join("\n")
  await writeFile(outputFile, output, "utf-8")
  console.log(`pgstrap: Types written to ${outputFile}`)

  await db.close()
}

function pgTypeToTs(
  dataType: string,
  udtName: string,
  enumMap: Map<string, string[]>
): string {
  // Check if it's an enum
  if (dataType === "USER-DEFINED" && enumMap.has(udtName)) {
    return toPascalCase(udtName)
  }

  switch (dataType) {
    case "integer":
    case "bigint":
    case "smallint":
    case "numeric":
    case "decimal":
    case "real":
    case "double precision":
    case "serial":
    case "bigserial":
    case "smallserial":
      return "number"

    case "text":
    case "character varying":
    case "varchar":
    case "char":
    case "character":
    case "citext":
      return "string"

    case "boolean":
      return "boolean"

    case "json":
    case "jsonb":
      return "Record<string, unknown>"

    case "timestamp without time zone":
    case "timestamp with time zone":
    case "timestamp":
    case "date":
    case "time":
    case "time without time zone":
    case "time with time zone":
      return "Date"

    case "uuid":
      return "string"

    case "bytea":
      return "Uint8Array"

    case "interval":
      return "string"

    case "inet":
    case "cidr":
    case "macaddr":
      return "string"

    case "ARRAY": {
      // Determine the element type from udtName (e.g., "_int4" -> "number")
      const elementType = arrayUdtToTs(udtName)
      return `${elementType}[]`
    }

    default:
      return "unknown"
  }
}

function arrayUdtToTs(udtName: string): string {
  // PG array udt_names start with underscore
  const base = udtName.startsWith("_") ? udtName.slice(1) : udtName
  switch (base) {
    case "int2":
    case "int4":
    case "int8":
    case "float4":
    case "float8":
    case "numeric":
      return "number"
    case "text":
    case "varchar":
    case "bpchar":
    case "uuid":
      return "string"
    case "bool":
      return "boolean"
    case "json":
    case "jsonb":
      return "Record<string, unknown>"
    case "timestamp":
    case "timestamptz":
    case "date":
      return "Date"
    default:
      return "unknown"
  }
}

function toPascalCase(str: string): string {
  return str
    .split(/[_\s-]+/)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1).toLowerCase())
    .join("")
}

function escapeIdentifier(name: string): string {
  // If the name contains special characters or is a reserved word, quote it
  if (/^[a-zA-Z_][a-zA-Z0-9_]*$/.test(name) && !isReservedWord(name)) {
    return name
  }
  return `"${name}"`
}

function isReservedWord(word: string): boolean {
  const reserved = new Set([
    "break", "case", "catch", "class", "const", "continue", "debugger",
    "default", "delete", "do", "else", "export", "extends", "false",
    "finally", "for", "function", "if", "import", "in", "instanceof",
    "new", "null", "return", "super", "switch", "this", "throw", "true",
    "try", "typeof", "var", "void", "while", "with", "yield",
    "enum", "implements", "interface", "let", "package", "private",
    "protected", "public", "static", "type",
  ])
  return reserved.has(word.toLowerCase())
}
